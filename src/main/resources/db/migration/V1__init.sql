-- Migración inicial: salas y reservas.
-- SQL compatible con H2 y PostgreSQL.

create table rooms (
    id          bigint generated by default as identity primary key,
    name        varchar(120) not null,
    capacity    integer       not null,
    location    varchar(200),
    constraint uk_rooms_name unique (name),
    constraint ck_rooms_capacity check (capacity > 0)
);

create table reservations (
    id                bigint generated by default as identity primary key,
    room_id           bigint       not null,
    responsable       varchar(120) not null,
    responsable_email varchar(160),
    start_time        timestamp    not null,
    end_time          timestamp    not null,
    status            varchar(20)  not null default 'ACTIVA',
    created_at        timestamp    not null default current_timestamp,
    constraint fk_reservations_room foreign key (room_id) references rooms (id),
    constraint ck_reservations_range check (start_time < end_time)
);

create index ix_reservations_room on reservations (room_id);
create index ix_reservations_start on reservations (start_time);

